    KEY idx_feishu_status (status),
    KEY idx_feishu_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='飞书图片接入任务记录';
